# Regenerates docs/reference/file-map.md from the "// FILE-MAP: <purpose>" header comment
# that must be the first line of every hand-written .cs file under src/. Never hand-edit
# file-map.md directly - edit the header comment in the source file and re-run this script.
# See .claude/rules/documentation.md ("generate the generatable") and
# plan/archive/task-a-doc-architecture.md section 3.
#
# Uses raw [System.IO.File] read/write (not Get-Content/Set-Content -Encoding utf8) because
# Windows PowerShell 5.1's encoding cmdlets misdetect UTF-8-without-BOM source files under a
# non-UTF8 system codepage and mangle multi-byte characters (e.g. an em-dash) - confirmed by
# running this script for real, not assumed.

$ErrorActionPreference = "Stop"
$bt = [char]96  # backtick, built via char code to avoid escaping headaches in double-quoted strings
$repoRoot = Split-Path -Parent $PSScriptRoot
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

$srcFiles = Get-ChildItem -Path (Join-Path $repoRoot "src") -Recurse -Filter "*.cs" |
    Where-Object { $_.FullName -notmatch '[\\/](obj|bin)[\\/]' } |
    Sort-Object FullName

$rows = @()
$missing = @()
foreach ($file in $srcFiles) {
    $firstLine = [System.IO.File]::ReadAllLines($file.FullName, [System.Text.Encoding]::UTF8)[0]
    $relPath = $file.FullName.Substring($repoRoot.Length + 1).Replace('\', '/')
    if ($firstLine -match '^// FILE-MAP: (.+)$') {
        $rows += [PSCustomObject]@{ Path = $relPath; Purpose = $Matches[1] }
    } else {
        $missing += $relPath
    }
}

if ($missing.Count -gt 0) {
    Write-Warning "Files missing a '// FILE-MAP: <purpose>' first line (excluded from the map):"
    $missing | ForEach-Object { Write-Warning "  $_" }
}

$sha = (git -C $repoRoot rev-parse --short HEAD 2>$null)
if (-not $sha) { $sha = "unknown" }

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("<!-- last-verified: $sha -->")
$lines.Add("<!-- GENERATED by scripts/generate-file-map.ps1 from each file's FILE-MAP header. Do not hand-edit. -->")
$lines.Add("# File map")
$lines.Add("")
$lines.Add("**Diataxis type:** reference (generated). Regenerate with " + $bt + $bt + "pwsh scripts/generate-file-map.ps1" + $bt + $bt + " after")
$lines.Add("adding, removing, or repurposing a source file - its " + $bt + $bt + "// FILE-MAP:" + $bt + $bt + " comment first line is the source of truth.")
$lines.Add("")
$lines.Add("| File | Purpose |")
$lines.Add("|---|---|")
foreach ($row in $rows) {
    $lines.Add("| " + $bt + $bt + $row.Path + $bt + $bt + " | " + $row.Purpose + " |")
}

$outPath = Join-Path $repoRoot "docs/reference/file-map.md"
[System.IO.File]::WriteAllText($outPath, ($lines -join "`n") + "`n", $utf8NoBom)
Write-Host "Wrote $outPath ($($rows.Count) files mapped, $($missing.Count) missing a header)"
